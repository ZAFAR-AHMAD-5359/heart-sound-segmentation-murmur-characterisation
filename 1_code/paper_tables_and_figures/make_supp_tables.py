ci = lambda c, fmt='%.1f': '[' + (fmt % c[0]) + ', ' + (fmt % c[1]) + ']'
sgn = lambda v, fmt='%.1f': ('+' if v >= 0 else '$-$') + (fmt % abs(v))
sci = lambda c, fmt='%.1f': '[' + sgn(c[0], fmt) + ', ' + sgn(c[1], fmt) + ']'
APOS = "'"
WIDE = {'tab:Ssubgroups', 'tab:Snoiseseg', 'tab:Snoiseboth'}                 # set landscape
SEP = {'tab:Sexp0b': '2pt'}               # tighter columns


def stable(name, caption, label, colspec, header, rows, size='\\footnotesize'):
    env = 'sidewaystable' if label in WIDE else 'table'
    opt = '' if env == 'sidewaystable' else '[htbp]'
    sep = SEP.get(label, '3pt')
    text = ('%% generated by 00_admin/make_supp_tables.py\n\\begin{' + env + '}' + opt + '\n\\centering\n\\caption{' + caption + '}\n\\label{' + label + '}\n'
            + size + '\n\\setlength{\\tabcolsep}{' + sep + '}\n\\begin{tabular}{' + colspec + '}\n\\toprule\n' + header + ' \\\\\n\\midrule\n'
            + '\n'.join(rows) + '\n\\bottomrule\n\\end{tabular}\n\\end{' + env + '}\n')
    with open(os.path.join(STAB, name), 'w', encoding='utf-8') as fh:
        fh.write(text)
    print('wrote', name)


