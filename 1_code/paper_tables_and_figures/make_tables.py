"""Generate the results tables of the revised manuscript from the analysis outputs copied into 06_results.
No value is typed by hand. Writes 01_manuscript/tables/tab_results.tex, tab_contrasts.tex, tab_subgroups.tex and
02_supplement/tables/tabS_metrics.tex.

Run:  python make_tables.py
"""
import json, os

PKG = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(PKG, '06_results')
TAB = os.environ.get('TAB_OVERRIDE') or os.path.join(PKG, '01_manuscript', 'tables')
STAB = os.path.join(PKG, '02_supplement', 'tables')
os.makedirs(STAB, exist_ok=True)
K = dict(E='equal_time', A='syn_fixed', B='syn_fusion', S='springer_wpk', S_pub='springer_pub', T='timing_net', W='waveform_net',
         D='pcg_seg_fixed', C='pcg_seg', S_annot='springer_wpk_annot', T_annot='timing_net_annot', W_annot='waveform_net_annot',
         E2='equal_time_matched')
LABEL = dict(E='E, equal-time', E2='E2, equal pseudo-cycles', A='A, synthetic ECG, fixed', B='B, synthetic ECG, refined', S='S, Springer',
             S_pub='S\\textsubscript{pub}, Springer, published', T='T, timing network', W='W, waveform network', D='D, annotated S1, fixed phases',
             C='C, expert-reviewed')
ORDER = ('E', 'E2', 'A', 'B', 'S', 'S_pub', 'T', 'W', 'D', 'C')

st = json.load(open(os.path.join(RES, 'run2_scoring', 'stats_results.json')))
est = json.load(open(os.path.join(RES, 'run2_scoring', 'estimation_contrasts.json')))
sub = json.load(open(os.path.join(RES, 'run2_estimation', 'run2_estimation.json')))
rc = json.load(open(os.path.join(RES, 'revision_checks', 'revision_checks.json')))
cnn_stats = json.load(open(os.path.join(RES, 'run1_stats', 'cnn_stats.json')))
_e2p = os.environ.get('EXP2_RESULTS') or os.path.join(RES, 'exp2_analysis', 'exp2_results.json')
E2 = json.load(open(_e2p)) if os.path.exists(_e2p) else None     # Experiment 2 (acoustic-label control T_ac), when scored
f1 = lambda v: '%.1f' % v
ci = lambda c, fmt='%.1f': '[' + (fmt % c[0]) + ', ' + (fmt % c[1]) + ']'
sgn = lambda v, fmt='%.1f': ('+' if v >= 0 else '$-$') + (fmt % abs(v))
sci = lambda c, fmt='%.1f': '[' + sgn(c[0], fmt) + ', ' + sgn(c[1], fmt) + ']'
R = lambda s: '\\rev{%s}' % s


def write(path, text):
    with open(path, 'w', encoding='utf-8') as fh:
        fh.write(text)
    print('wrote', os.path.relpath(path, PKG))


# ------------------------------------------------------------------ Table 3: arms
m, rf = st['mlp'], st['rf']
rows = []
for a in ORDER:
    pt = lambda t: m['per_task']['%s/%s' % (t, K[a])]['point']
    comp = m['composite'][K[a]]
    bold = a in ('T', 'W')
    cell = lambda s: ('\\textbf{%s}' % s) if bold else s
    rows.append(' & '.join(R(x) for x in (LABEL[a], cell(f1(comp['point'])), ci(comp['ci95']), f1(pt('grading')), f1(pt('timing')), f1(pt('shape')),
                                            f1(pt('detection')), f1(rf['composite'][K[a]]['point']))) + ' \\\\')
    if a == 'T' and E2 is not None:
        _c, _p = E2['composite']['timing_net_ac'], E2['per_task']['timing_net_ac']
        rows.append(' & '.join(R(x) for x in ('T\\textsubscript{ac}, acoustic-label control', f1(_c['point']), ci(_c['ci95']), f1(_p['grading']), f1(_p['timing']),
                                                f1(_p['shape']), f1(E2['detection']['timing_net_ac']['point']) if 'detection' in E2 else '',
                                                f1(E2['estimation']['rf_composite']['timing_net_ac']))) + ' \\\\')
write(os.path.join(TAB, 'tab_results.tex'), r'''%% ===== TABLE 3: macro-F1 by arm (generated by 00_admin/make_tables.py) =====
\begin{table}[tbp]
\centering
\caption{\rev{Macro-F1 (\%%) by source of the cardiac-phase boundaries (3{,}000 recordings, 816 participants; participant-grouped ten-fold cross-validation). Composite: mean macro-F1 of the multilayer perceptron over grading, timing, and shape, the pre-registered endpoint, with its 95\%% participant-bootstrap interval. C gives reference values. ECG, electrocardiogram; RF, random forest.}}
\label{tab:results}
\footnotesize
\setlength{\tabcolsep}{3pt}
\begin{tabular}{@{}lrlrrrrr@{}}
\toprule
\rev{Arm} & \multicolumn{2}{c}{\rev{Composite [95\%% CI]}} & \rev{Grading} & \rev{Timing} & \rev{Shape} & \rev{Detection} & \rev{RF composite} \\
\midrule
%s
\bottomrule
\end{tabular}
\end{table}
''' % '\n'.join(rows))

# ------------------------------------------------------------------ Table 4: hypotheses and contrasts
H = m['hypotheses']
lv = lambda d: ('%.4f' % d['level']).rstrip('0')
h12 = lambda d: ('null rejected at 0.0125' if d['p1_25'] > 0 else 'null rejected at %s' % lv(d)) if d['rejected'] else 'not rejected'
hy = [('H1', 'S above E', H['H1'], h12(H['H1'])),
      ('H2', 'T above E', H['H2'], h12(H['H2'])),
      ('H3', 'T non-inferior to S, margin 2.5', H['H3'], '%s at %s' % (H['H3']['verdict'], lv(H['H3']))),
      ('H4', 'T above S', H['H4'], ('null rejected at %s; not at 0.0125' % lv(H['H4'])) if H['H4']['rejected'] else 'not rejected')]
rows = []
for h, lab, d, verdict in hy:
    rows.append(' & '.join(R(x) for x in ('%s: %s' % (h, lab), sgn(d['point']), sci(d['ci95']), sgn(d['p1_25'], '%.2f'), verdict)) + ' \\\\')
rows.append('\\midrule')
rows.append('\\multicolumn{5}{@{}l}{\\rev{Estimation, composite macro-F1 difference (no hypothesis test)}} \\\\')
pairs = [('W $-$ E', 'waveform_net', 'equal_time', None), ('A $-$ E', 'syn_fixed', 'equal_time', 'adversarial generator, fixed phases'),
         ('B $-$ E', 'syn_fusion', 'equal_time', 'adversarial generator, refined phases'),
         ('W $-$ T', 'waveform_net-timing_net', None, 'reconstruction against direct timing'),
         ('W $-$ S', 'waveform_net-springer_wpk', None, ''), ('T $-$ A', 'timing_net-syn_fixed', None, ''),
         ('T $-$ B', 'timing_net-syn_fusion', None, ''), ('W $-$ B', 'waveform_net-syn_fusion', None, '')]
for lab, key, ref, note in pairs:
    d = m['vs_E'][key] if ref == 'equal_time' else est[key]
    rows.append(' & '.join(R(x) for x in (lab, sgn(d['point']), sci(d['ci95']), '', note or '')) + ' \\\\')
for lab, key, note in (('T $-$ S\\textsubscript{pub}', 'T_minus_Spub', 'published Springer rule'), ('W $-$ S\\textsubscript{pub}', 'W_minus_Spub', ''),
                       ('S\\textsubscript{pub} $-$ S', 'Spub_minus_S', '')):
    d = rc['spub'][key]
    rows.append(' & '.join(R(x) for x in (lab, sgn(d['point']), sci(d['ci95']), '', note)) + ' \\\\')
if E2 is not None:
    rows.append('\\midrule')
    rows.append('\\multicolumn{5}{@{}l}{\\rev{Acoustic-label control T\\textsubscript{ac}, pre-registered after the main results (one two-sided hypothesis at 0.05)}} \\\\')
    _h = E2['H1']
    _read = {True: 'T above T\\textsubscript{ac}', False: 'T\\textsubscript{ac} above T'}.get(True if _h['ci95'][0] > 0 else (False if _h['ci95'][1] < 0 else None), 'no difference shown; no equivalence margin')
    rows.append(' & '.join(R(x) for x in ('T $-$ T\\textsubscript{ac}', sgn(_h['point']), sci(_h['ci95']), '', _read)) + ' \\\\')
    for _lab, _k in (('T\\textsubscript{ac} $-$ E', 'T_ac_minus_E'), ('T\\textsubscript{ac} $-$ S', 'T_ac_minus_S'), ('T\\textsubscript{ac} $-$ S\\textsubscript{pub}', 'T_ac_minus_S_pub')):
        _d = E2['estimation'][_k]
        rows.append(' & '.join(R(x) for x in (_lab, sgn(_d['point']), sci(_d['ci95']), '', '')) + ' \\\\')
    _r = E2['estimation']['recovery_T_ac']
    rows.append(' & '.join(R(x) for x in ('Recovery fraction, T\\textsubscript{ac}', '%.2f' % _r['point'], ci(_r['ci95'], '%.2f') if _r['ci95'] else '', '', 'matched coverage')) + ' \\\\')
rows.append('\\midrule')
rows.append('\\multicolumn{5}{@{}l}{\\rev{Relative to the expert-reviewed reference, matched coverage only}} \\\\')
for lab, key in (('T', 'timing_net_annot'), ('W', 'waveform_net_annot'), ('S', 'springer_wpk_annot')):
    d = m['recovery_fraction'][key]
    rows.append(' & '.join(R(x) for x in ('Recovery fraction, ' + lab, '%.2f' % d['point'], ci(d['ci95'], '%.2f'), '', '$(X - E)/(C - E)$' if lab == 'T' else '')) + ' \\\\')
for lab, key in (('T', 'T_annot'), ('W', 'W_annot'), ('S', 'S_annot')):
    d = rc['matched_coverage_vs_C'][key]
    rows.append(' & '.join(R(x) for x in ('C $-$ ' + lab + '\\textsubscript{annot}', sgn(d['point']), sci(d['ci95']), '', 'composite points, matched coverage' if lab == 'T' else '')) + ' \\\\')
rows.append('\\midrule')
rows.append('\\multicolumn{5}{@{}l}{\\rev{Detection macro-F1 against the PCG-only CNN (%s; composite: CNN %s)}} \\\\' % (
    f1(sub['cnn']['detection']['CNN']['point']), f1(sub['cnn']['cnn_composite']['point'])))
for k in ('T-CNN', 'W-CNN', 'S-CNN'):
    d = sub['cnn']['detection_vs_cnn'][k]
    rows.append(' & '.join(R(x) for x in (k.replace('-', ' $-$ ') + ', detection', sgn(d['point']), sci(d['ci95']), '', '')) + ' \\\\')
d = sub['cnn']['composite_T_minus_CNN']
rows.append(' & '.join(R(x) for x in ('T $-$ CNN, composite', sgn(d['point']), sci(d['ci95']), '', '')) + ' \\\\')
write(os.path.join(TAB, 'tab_contrasts.tex'), r'''%% ===== TABLE 4: pre-registered hypotheses and estimation contrasts (generated by 00_admin/make_tables.py) =====
\begin{table}[tbp]
\centering
\caption{\rev{Pre-registered hypotheses and estimated contrasts (composite macro-F1 points unless stated; 95\%% participant-bootstrap intervals). H1 and H2 were one-sided at 0.0125 each (total alpha 0.025); both nulls were rejected, so H3 and H4 were tested at 0.025. The 1.25th percentile decides at 0.0125 and the 2.5th at 0.025. CNN, convolutional neural network; PCG, phonocardiogram.}}
\label{tab:contrasts}
\footnotesize
\setlength{\tabcolsep}{3pt}
\begin{tabularx}{\textwidth}{@{}lrlr>{\raggedright\arraybackslash}X@{}}
\toprule
\rev{Contrast} & \multicolumn{2}{c}{\rev{Estimate [95\%% CI]}} & \rev{1.25th pct} & \rev{Verdict or note} \\
\midrule
%s
\bottomrule
\end{tabularx}
\end{table}
''' % '\n'.join(rows))

# ------------------------------------------------------------------ Table 5: heart-rate bands and infants
SUB = (('<100', 'below 100'), ('100-125', '100 to 125'), ('125-150', '125 to 150'), ('>=150', '150 or more'), ('infants', 'infants (under 1 year)'))
rows = []
for key, lab in (('full', 'all recordings'),) + SUB:
    s = sub['full'] if key == 'full' else sub['subsets'][key]
    c = s['composite']
    t = s['contrasts']
    cells = [lab, str(s['n']['grading']), f1(c['C']['point']), f1(c['T']['point']), f1(c['W']['point']), f1(c['S']['point']), f1(c['E']['point']),
             sgn(t['T-E']['point']) + ' ' + sci(t['T-E']['ci95']), sgn(t['T-S']['point']) + ' ' + sci(t['T-S']['ci95']),
             sgn(t['W-S']['point']) + ' ' + sci(t['W-S']['ci95'])]
    rows.append(' & '.join(R(x) for x in cells) + ' \\\\')
write(os.path.join(TAB, 'tab_subgroups.tex'), r'''%% ===== TABLE 5: heart-rate bands and infants (generated by 00_admin/make_tables.py) =====
\begin{table}[tbp]
\centering
\caption{\rev{Composite macro-F1 by heart rate (beats per minute, from the annotated cycles) and in infants, with differences and 95\%% participant-bootstrap intervals. Estimation only, without multiplicity control. n, grading recordings.}}
\label{tab:subgroups}
\scriptsize
\setlength{\tabcolsep}{3pt}
\begin{tabular}{@{}lrrrrrrlll@{}}
\toprule
\rev{Subset} & \rev{n} & \rev{C} & \rev{T} & \rev{W} & \rev{S} & \rev{E} & \rev{T $-$ E} & \rev{T $-$ S} & \rev{W $-$ S} \\
\midrule
%s
\bottomrule
\end{tabular}
\end{table}
''' % '\n'.join(rows))

# ------------------------------------------------------------------ Supplement table: secondary metrics (R3-M5)
p = os.path.join(RES, 'secondary_metrics', 'secondary_metrics.json')
if os.path.exists(p):
    sm = json.load(open(p))['results']
    CLS = dict(detection=('absent', 'present'), grading=('I/VI', 'II/VI', 'III/VI+'), timing=('holo', 'early', 'mid'), shape=('plateau', 'decresc.', 'diamond'))
    rows = []
    for t in ('detection', 'grading', 'timing', 'shape'):
        rows.append('\\multicolumn{6}{@{}l}{\\textit{%s} (classes: %s)} \\\\' % (t.capitalize(), ', '.join(CLS[t])))
        for a in tuple(x for x in ORDER if x != 'E2') + ('CNN',):
            r = sm['%s/%s' % (t, a)]
            lab = {'S_pub': 'S' + chr(92) + 'textsubscript{pub}'}.get(a, a)
            mf = st['mlp']['per_task']['%s/%s' % (t, K[a])] if a != 'CNN' else cnn_stats['per_task'][t]
            rows.append(' & '.join((lab, '%.1f %s' % (mf['point'], ci(mf['ci95'])),
                                    '%.3f %s' % (r['balanced_accuracy']['point'], ci(r['balanced_accuracy']['ci95'], '%.3f')),
                                    ' / '.join('%.2f' % x['point'] for x in r['sensitivity']),
                                    '%.3f %s' % (r['auroc']['point'], ci(r['auroc']['ci95'], '%.3f')),
                                    '%.3f %s' % (r['auprc']['point'], ci(r['auprc']['ci95'], '%.3f')))) + ' \\\\')
        rows.append('\\addlinespace')
    write(os.path.join(STAB, 'tabS_metrics.tex'), r'''%% ===== Supplement table: secondary metrics (generated by 00_admin/make_tables.py) =====
\begin{table}[p]
\centering
\caption{Per-task metrics of every arm (multilayer perceptron, out-of-fold, five-seed ensemble; the CNN from its own predictions on the same rows). Macro-F1 in per cent; balanced accuracy is the mean class recall; sensitivities are class recalls in the order listed; AUROC is the one-against-rest macro average and AUPRC the macro average precision (detection: the murmur-present class). Brackets: 95\%% participant-bootstrap intervals (2{,}000 shared draws). Descriptive; defined after the pre-registration.}
\label{tab:Smetrics}
\scriptsize
\setlength{\tabcolsep}{2.5pt}
\begin{tabular}{@{}llllll@{}}
\toprule
Arm & Macro-F1 & Balanced accuracy & Sensitivity by class & AUROC & AUPRC \\
\midrule
%s
\bottomrule
\end{tabular}
\end{table}
''' % '\n'.join(rows[:-1]))
else:
    print('secondary metrics not yet available:', p)
